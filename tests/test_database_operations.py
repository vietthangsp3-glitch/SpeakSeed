def test_install_seed_preserves_published_content_and_removes_accounts(tmp_path):
    from pathlib import Path
    root = Path(__file__).resolve().parents[1]; seed = tmp_path / "seed.db"
    create_seed(root / "speakseed.db", seed)
    with sqlite3.connect(seed) as con:
        assert con.execute("SELECT COUNT(*) FROM users").fetchone()[0] == 0
        assert con.execute("SELECT COUNT(*) FROM library_words WHERE reviewed=1").fetchone()[0] == 6280
        assert con.execute("SELECT COUNT(*) FROM grammar_lessons WHERE published=1").fetchone()[0] == 100
        assert con.execute("SELECT COUNT(*) FROM grammar_exercises WHERE published=1").fetchone()[0] == 1000


def test_postgres_adapter_qualifies_upsert_target_columns():
    sql = _postgres_sql("""INSERT INTO progress(user_id,word_id,correct,wrong) VALUES(?,?,?,?)
        ON CONFLICT(user_id,word_id) DO UPDATE SET correct=correct+excluded.correct,
        wrong=wrong+excluded.wrong""")
    assert "correct=progress.correct+excluded.correct" in sql
    assert "wrong=progress.wrong+excluded.wrong" in sql


def test_hybrid_row_preserves_duplicate_postgres_columns_by_position():
    row = HybridRow((2, 1, 10), ["count", "coalesce", "count"])
    attempted, solved, total = row
    assert [attempted, solved, total] == [2, 1, 10]
    assert dict(row) == {"count": 2, "coalesce": 1, "count_2": 10}

