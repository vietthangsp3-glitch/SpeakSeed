def test_verified_backup_restore_preserves_all_counts(tmp_path):
    source = tmp_path / "source.db"; saved = tmp_path / "backup.db"; restored = tmp_path / "restored.db"
    # Use the real schema files but isolated data.
    from pathlib import Path
    root = Path(__file__).resolve().parents[1]
    run_migrations(source, root / "migrations")
    with sqlite3.connect(source) as con:
        con.execute("INSERT INTO users(name,email,salt,hash,created) VALUES('A','a@example.com','s','h','now')")
    manifest_path = backup(source, saved)
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    restore(saved, restored)
    assert manifest["table_counts"]["users"] == 1
    with sqlite3.connect(restored) as con:
        assert con.execute("PRAGMA integrity_check").fetchone()[0] == "ok"
        assert con.execute("SELECT email FROM users").fetchone()[0] == "a@example.com"


def test_postgres_migration_plan_covers_schema_without_writing(tmp_path):
    from pathlib import Path
    root = Path(__file__).resolve().parents[1]; source = tmp_path / "source.db"
    run_migrations(source, root / "migrations")
    plan = inspect(source)
    names = {table["name"] for table in plan["tables"]}
    assert {"library_words", "grammar_lessons", "grammar_exercises", "users", "sessions", "ai_usage"} <= names
    assert plan["foreign_keys"] > 0
    users = next(table for table in plan["tables"] if table["name"] == "users")
    ddl = table_ddl(users)
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    words = next(table for table in plan["tables"] if table["name"] == "library_words")
    partial = next(sql for sql in index_ddls(words) if "idx_library_words_one_published" in sql)
    assert "WHERE reviewed=1 AND normalized_word != ''" in partial
    assert plan["latest_schema_version"] == "022_wordnet_topic_classification.sql"


