"""Plan and explicitly apply a lossless SQLite -> PostgreSQL copy.

The default action is read-only planning. `--apply` requires an empty target database,
runs in one transaction, validates counts, then leaves the SQLite source untouched.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sqlite3
from pathlib import Path


MINIMUM_SCHEMA_VERSION = "022_wordnet_topic_classification.sql"
REQUIRED_TABLE_COUNT = 65
REQUIRED_PUBLISHED_CONTENT = {
    "published_words": 6280,
    "published_grammar_lessons": 100,
    "published_grammar_exercises": 1000,
}


def qi(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def pg_type(sqlite_type: str) -> str:
    value = sqlite_type.upper()
    if "INT" in value: return "BIGINT"
    if any(item in value for item in ("REAL", "FLOA", "DOUB")): return "DOUBLE PRECISION"
    if "BLOB" in value: return "BYTEA"
    if any(item in value for item in ("NUM", "DEC")): return "NUMERIC"
    return "TEXT"


def pg_default(value) -> str:
    if value is None: return ""
    text = str(value).strip()
    upper = text.upper()
    if upper in {"CURRENT_TIMESTAMP", "CURRENT_DATE", "CURRENT_TIME"}: return " DEFAULT " + upper
    if text.startswith("'") and text.endswith("'"): return " DEFAULT " + text
    try:
        float(text); return " DEFAULT " + text
    except ValueError:
        return ""


def inspect(source: Path) -> dict:
    uri = f"file:{source.resolve().as_posix()}?mode=ro"
    con = sqlite3.connect(uri, uri=True); con.row_factory = sqlite3.Row
    try:
        if con.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
            raise RuntimeError("SQLite integrity_check thất bại")
        fk_errors = con.execute("PRAGMA foreign_key_check").fetchall()
        if fk_errors: raise RuntimeError(f"SQLite có {len(fk_errors)} lỗi foreign key")
        tables = []
        for row in con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"):
            name = row[0]
            columns = [dict(item) for item in con.execute(f"PRAGMA table_info({qi(name)})")]
            foreign_keys = [dict(item) for item in con.execute(f"PRAGMA foreign_key_list({qi(name)})")]
            indexes = []
            for idx in con.execute(f"PRAGMA index_list({qi(name)})"):
                if idx[3] == "pk": continue
                cols = [part[2] for part in con.execute(f"PRAGMA index_info({qi(idx[1])})")]
                source_sql = con.execute("SELECT sql FROM sqlite_master WHERE type='index' AND name=?", (idx[1],)).fetchone()
                where = ""
                if source_sql and source_sql[0]:
                    match = re.search(r"\sWHERE\s+(.+)$", source_sql[0], re.I | re.S)
                    where = match.group(1).strip() if match else ""
                if cols: indexes.append({"name": idx[1], "unique": bool(idx[2]), "columns": cols,
                                         "origin": idx[3], "where": where})
            tables.append({"name": name, "count": con.execute(f"SELECT COUNT(*) FROM {qi(name)}").fetchone()[0],
                           "columns": columns, "foreign_keys": foreign_keys, "indexes": indexes})
        latest = con.execute(
            "SELECT version FROM schema_migrations ORDER BY version DESC LIMIT 1"
        ).fetchone()
        content = {
            "published_words": con.execute(
                "SELECT COUNT(*) FROM library_words WHERE reviewed=1"
            ).fetchone()[0],
            "published_grammar_lessons": con.execute(
                "SELECT COUNT(*) FROM grammar_lessons WHERE published=1"
            ).fetchone()[0],
            "published_grammar_exercises": con.execute(
                "SELECT COUNT(*) FROM grammar_exercises WHERE published=1"
            ).fetchone()[0],
        }
        return {"source": str(source.resolve()), "tables": tables,
                "total_rows": sum(table["count"] for table in tables),
                "foreign_keys": sum(len(table["foreign_keys"]) for table in tables),
                "latest_schema_version": latest[0] if latest else "", "content": content}
    finally:
        con.close()


def table_ddl(table: dict) -> str:
    primary = sorted((column for column in table["columns"] if column["pk"]), key=lambda x: x["pk"])
    single_identity = len(primary) == 1 and "INT" in primary[0]["type"].upper()
    definitions = []
    for column in table["columns"]:
        definition = f'{qi(column["name"])} {pg_type(column["type"])}'
        if single_identity and column["pk"]:
            definition += " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        else:
            if column["notnull"]: definition += " NOT NULL"
            definition += pg_default(column["dflt_value"])
        definitions.append(definition)
    if primary and not single_identity:
        definitions.append("PRIMARY KEY (" + ",".join(qi(column["name"]) for column in primary) + ")")
    return f'CREATE TABLE {qi(table["name"])} (\n  ' + ",\n  ".join(definitions) + "\n)"


def fk_ddls(table: dict) -> list[str]:
    grouped: dict[int, list[dict]] = {}
    for key in table["foreign_keys"]: grouped.setdefault(key["id"], []).append(key)
    result = []
    for ident, keys in grouped.items():
        keys.sort(key=lambda x: x["seq"]); target = keys[0]["table"]
        name = f'fk_{table["name"]}_{ident}'
        sql = (f'ALTER TABLE {qi(table["name"])} ADD CONSTRAINT {qi(name)} FOREIGN KEY (' +
               ",".join(qi(key["from"]) for key in keys) + ") REFERENCES " + qi(target) + " (" +
               ",".join(qi(key["to"]) for key in keys) + ")")
        if keys[0]["on_update"] != "NO ACTION": sql += " ON UPDATE " + keys[0]["on_update"]
        if keys[0]["on_delete"] != "NO ACTION": sql += " ON DELETE " + keys[0]["on_delete"]
        result.append(sql)
    return result


def index_ddls(table: dict) -> list[str]:
    result = []
    for index in table["indexes"]:
        # SQLite autoindexes represent UNIQUE constraints; recreate as unique indexes.
        name = index["name"] if not index["name"].startswith("sqlite_autoindex") else f'uq_{table["name"]}_' + "_".join(index["columns"])
        statement = f'CREATE {"UNIQUE " if index["unique"] else ""}INDEX {qi(name)} ON {qi(table["name"])} (' + \
                    ",".join(qi(column) for column in index["columns"]) + ")"
        if index.get("where"):
            statement += " WHERE " + index["where"]
        result.append(statement)
    return result


def validate_release_source(plan: dict) -> None:
    """Refuse an incomplete release database before opening the target."""
    names = {table["name"] for table in plan["tables"]}
    if len(names) < REQUIRED_TABLE_COUNT or "schema_migrations" not in names:
        raise RuntimeError(
            f"SQLite nguồn chưa đủ schema: {len(names)}/{REQUIRED_TABLE_COUNT} bảng"
        )
    if plan.get("latest_schema_version", "") < MINIMUM_SCHEMA_VERSION:
        raise RuntimeError(
            f"SQLite nguồn cần schema tối thiểu {MINIMUM_SCHEMA_VERSION}; "
            f"hiện có {plan.get('latest_schema_version') or 'none'}"
        )
    for key, expected in REQUIRED_PUBLISHED_CONTENT.items():
        actual = plan.get("content", {}).get(key)
        # Vocabulary is an intentionally extensible catalog.  The verified 4,213
        # records are a floor, whereas the Phase 2 grammar curriculum is a fixed
        # release whose exact counts protect against accidental duplication.
        if key == "published_words":
            if actual is None or actual < expected:
                raise RuntimeError(
                    f"SQLite nguồn có {key}={actual}; yêu cầu tối thiểu {expected}"
                )
        elif actual != expected:
            raise RuntimeError(f"SQLite nguồn có {key}={actual}; yêu cầu chính xác {expected}")


def apply(source: Path, target_url: str, plan: dict) -> None:
    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError("Cài dependency psycopg[binary] trước khi --apply") from exc
    src = sqlite3.connect(f"file:{source.resolve().as_posix()}?mode=ro", uri=True)
    src.row_factory = sqlite3.Row
    with psycopg.connect(target_url) as target:
        with target.cursor() as cursor:
            cursor.execute("SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='public'")
            if cursor.fetchone()[0]: raise RuntimeError("PostgreSQL đích phải trống để tránh ghi đè dữ liệu")
            for table in plan["tables"]: cursor.execute(table_ddl(table))
            for table in plan["tables"]:
                columns = [column["name"] for column in table["columns"]]
                rows = src.execute(f'SELECT * FROM {qi(table["name"])}').fetchall()
                if rows:
                    sql = f'INSERT INTO {qi(table["name"])} (' + ",".join(qi(c) for c in columns) + ") VALUES (" + ",".join(["%s"] * len(columns)) + ")"
                    cursor.executemany(sql, [tuple(row[column] for column in columns) for row in rows])
            for table in plan["tables"]:
                for sql in fk_ddls(table) + index_ddls(table): cursor.execute(sql)
                primary = [column for column in table["columns"] if column["pk"]]
                if len(primary) == 1 and "INT" in primary[0]["type"].upper() and table["count"]:
                    cursor.execute("SELECT setval(pg_get_serial_sequence(%s,%s), (SELECT MAX(" + qi(primary[0]["name"]) + ") FROM " + qi(table["name"]) + "))",
                                   (table["name"], primary[0]["name"]))
            for table in plan["tables"]:
                cursor.execute(f'SELECT COUNT(*) FROM {qi(table["name"])}')
                if cursor.fetchone()[0] != table["count"]: raise RuntimeError(f'Sai count: {table["name"]}')
        target.commit()
    src.close()


def main() -> None:
    parser = argparse.ArgumentParser(description="Migrate SpeakSeed data from SQLite to PostgreSQL")
    parser.add_argument("--source", type=Path, default=Path("speakseed.db"))
    parser.add_argument("--target-url", help="PostgreSQL URL; defaults to DATABASE_URL to avoid exposing secrets in process arguments")
    parser.add_argument("--apply", action="store_true", help="Write to an empty PostgreSQL database")
    parser.add_argument("--plan-json", type=Path, help="Save the inspectable migration plan")
    args = parser.parse_args(); plan = inspect(args.source)
    if args.plan_json:
        args.plan_json.parent.mkdir(parents=True, exist_ok=True)
        args.plan_json.write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"mode": "apply" if args.apply else "plan", "source": plan["source"],
                      "tables": len(plan["tables"]), "rows": plan["total_rows"],
                      "foreign_keys": plan["foreign_keys"],
                      "latest_schema_version": plan["latest_schema_version"],
                      "content": plan["content"]}, ensure_ascii=True))
    if args.apply:
        validate_release_source(plan)
        target_url=args.target_url or os.getenv("DATABASE_URL", "").strip()
        if not target_url or not target_url.startswith(("postgresql://", "postgres://")):
            raise SystemExit("Set DATABASE_URL or pass a valid PostgreSQL --target-url with --apply")
        apply(args.source, target_url, plan)
        print(json.dumps({"status": "validated", "source_preserved": True}, ensure_ascii=True))


if __name__ == "__main__":
    main()
