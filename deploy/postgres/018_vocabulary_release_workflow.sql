CREATE TABLE IF NOT EXISTS content_reviewer_roles(
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK(role IN ('reviewer','publisher','admin')),
  granted_by TEXT NOT NULL, granted_at TEXT NOT NULL, PRIMARY KEY(user_id,role)
);
CREATE TABLE IF NOT EXISTS vocabulary_quality_policies(
  version TEXT PRIMARY KEY, core_requirements_json TEXT NOT NULL,
  enriched_fields_json TEXT NOT NULL, active BIGINT NOT NULL DEFAULT 0 CHECK(active IN (0,1)),
  created_at TEXT NOT NULL
);
