CREATE TABLE IF NOT EXISTS vocabulary_candidates(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, stable_key TEXT NOT NULL UNIQUE,
  normalized_word TEXT NOT NULL, word TEXT NOT NULL, pos TEXT NOT NULL, meaning_vi TEXT NOT NULL DEFAULT '',
  ipa TEXT NOT NULL DEFAULT '', cefr_level TEXT NOT NULL CHECK(cefr_level IN ('A0','A1','A2','B1','B2','unverified')),
  definition_en TEXT NOT NULL DEFAULT '', example_en TEXT NOT NULL DEFAULT '', example_vi TEXT NOT NULL DEFAULT '',
  source_key TEXT NOT NULL REFERENCES content_sources(source_key), source_record_id TEXT NOT NULL,
  provenance_json TEXT NOT NULL, license_status TEXT NOT NULL CHECK(license_status IN ('pass','conditional','blocked')),
  qa_status TEXT NOT NULL CHECK(qa_status IN ('pass','warn','fail')),
  core_status TEXT NOT NULL CHECK(core_status IN ('review_ready','needs_data','license_blocked','duplicate','invalid')),
  review_status TEXT NOT NULL DEFAULT 'pending' CHECK(review_status IN ('pending','needs_revision','human_reviewed','rejected')),
  policy_version TEXT NOT NULL REFERENCES vocabulary_quality_policies(version), content_revision BIGINT NOT NULL DEFAULT 1 CHECK(content_revision>0),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL, reviewed_at TEXT,
  reviewed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  published_word_id BIGINT REFERENCES library_words(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS vocabulary_candidate_topics(
  candidate_id BIGINT NOT NULL REFERENCES vocabulary_candidates(id) ON DELETE CASCADE,
  topic_id BIGINT NOT NULL REFERENCES vocabulary_topics(id) ON DELETE CASCADE,
  confidence BIGINT NOT NULL CHECK(confidence BETWEEN 0 AND 100), source_key TEXT NOT NULL,
  rationale TEXT NOT NULL, review_status TEXT NOT NULL DEFAULT 'pending' CHECK(review_status IN ('pending','human_reviewed','rejected')),
  PRIMARY KEY(candidate_id,topic_id)
);
CREATE TABLE IF NOT EXISTS vocabulary_candidate_events(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id BIGINT NOT NULL REFERENCES vocabulary_candidates(id) ON DELETE CASCADE,
  actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT, actor_name TEXT NOT NULL,
  action TEXT NOT NULL CHECK(action IN ('approve','reject','needs_revision','edit','publish','rollback')),
  reason TEXT NOT NULL, policy_version TEXT NOT NULL, content_revision BIGINT NOT NULL, occurred_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS vocabulary_publish_batches(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publisher_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT, publisher_name TEXT NOT NULL,
  policy_version TEXT NOT NULL, status TEXT NOT NULL CHECK(status IN ('running','published','rolled_back','failed')),
  created_at TEXT NOT NULL, finished_at TEXT, report_json TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS vocabulary_publish_items(
  batch_id BIGINT NOT NULL REFERENCES vocabulary_publish_batches(id) ON DELETE RESTRICT,
  candidate_id BIGINT NOT NULL UNIQUE REFERENCES vocabulary_candidates(id) ON DELETE RESTRICT,
  word_id BIGINT NOT NULL REFERENCES library_words(id) ON DELETE RESTRICT,
  content_revision BIGINT NOT NULL, created_at TEXT NOT NULL, PRIMARY KEY(batch_id,candidate_id)
);
CREATE INDEX IF NOT EXISTS idx_vocabulary_candidates_queue ON vocabulary_candidates(review_status,core_status,cefr_level,source_key,id);
CREATE INDEX IF NOT EXISTS idx_vocabulary_candidate_topics_topic ON vocabulary_candidate_topics(topic_id,review_status,candidate_id);
CREATE INDEX IF NOT EXISTS idx_vocabulary_candidate_events_candidate ON vocabulary_candidate_events(candidate_id,occurred_at,id);
CREATE OR REPLACE FUNCTION block_vocabulary_event_changes() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RAISE EXCEPTION 'vocabulary candidate audit log is immutable'; END$$;
DROP TRIGGER IF EXISTS immutable_vocabulary_candidate_events_update ON vocabulary_candidate_events;
CREATE TRIGGER immutable_vocabulary_candidate_events_update BEFORE UPDATE OR DELETE ON vocabulary_candidate_events FOR EACH ROW EXECUTE FUNCTION block_vocabulary_event_changes();
CREATE OR REPLACE FUNCTION invalidate_vocabulary_candidate_approval_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.review_status='human_reviewed' THEN
  NEW.review_status='needs_revision'; NEW.reviewed_at=NULL; NEW.reviewed_by_user_id=NULL;
  NEW.content_revision=OLD.content_revision+1; NEW.updated_at=CURRENT_TIMESTAMP::text;
 END IF; RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS invalidate_vocabulary_candidate_approval ON vocabulary_candidates;
CREATE TRIGGER invalidate_vocabulary_candidate_approval BEFORE UPDATE OF word,pos,meaning_vi,ipa,cefr_level,definition_en,example_en,example_vi,provenance_json,license_status,qa_status,core_status ON vocabulary_candidates FOR EACH ROW EXECUTE FUNCTION invalidate_vocabulary_candidate_approval_fn();
CREATE OR REPLACE FUNCTION validate_vocabulary_candidate_human_review_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.review_status='human_reviewed' AND (NEW.core_status<>'review_ready' OR NEW.qa_status<>'pass'
  OR NEW.license_status<>'pass' OR btrim(NEW.meaning_vi)='' OR btrim(NEW.pos)='' OR NEW.cefr_level='unverified'
  OR NOT EXISTS(SELECT 1 FROM vocabulary_candidate_topics t WHERE t.candidate_id=NEW.id AND t.review_status='human_reviewed')
  OR NOT EXISTS(SELECT 1 FROM vocabulary_candidate_events e WHERE e.candidate_id=NEW.id AND e.action='approve' AND e.content_revision=NEW.content_revision AND btrim(e.actor_name)<>''))
 THEN RAISE EXCEPTION 'Core validation and current human review evidence are required'; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS validate_vocabulary_candidate_human_review ON vocabulary_candidates;
CREATE TRIGGER validate_vocabulary_candidate_human_review BEFORE UPDATE OF review_status ON vocabulary_candidates FOR EACH ROW EXECUTE FUNCTION validate_vocabulary_candidate_human_review_fn();
CREATE OR REPLACE FUNCTION validate_vocabulary_topic_publish_insert_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.published=1 AND NEW.review_status<>'existing_published' AND (NEW.review_status<>'human_reviewed'
  OR NOT EXISTS(SELECT 1 FROM vocabulary_topic_reviews r WHERE r.word_id=NEW.word_id AND r.topic_id=NEW.topic_id AND r.sense_key=NEW.sense_key AND r.decision='approve' AND btrim(r.reviewer_name)<>''))
 THEN RAISE EXCEPTION 'Human review evidence is required for a published topic mapping'; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS validate_vocabulary_topic_publish_insert ON vocabulary_topic_words;
CREATE TRIGGER validate_vocabulary_topic_publish_insert BEFORE INSERT ON vocabulary_topic_words FOR EACH ROW EXECUTE FUNCTION validate_vocabulary_topic_publish_insert_fn();
CREATE OR REPLACE FUNCTION validate_library_word_core_v1_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.reviewed=1 AND (btrim(NEW.normalized_word)='' OR btrim(NEW.meaning)='' OR btrim(NEW.pos)=''
  OR NEW.stage NOT IN ('A0','A1','A2','B1','B2') OR btrim(NEW.topic)='' OR btrim(NEW.source)='')
 THEN RAISE EXCEPTION 'published Core vocabulary is incomplete under core-v1'; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS validate_library_word_insert ON library_words;
DROP TRIGGER IF EXISTS validate_library_word_update ON library_words;
CREATE TRIGGER validate_library_word_insert BEFORE INSERT ON library_words FOR EACH ROW EXECUTE FUNCTION validate_library_word_core_v1_fn();
CREATE TRIGGER validate_library_word_update BEFORE UPDATE ON library_words FOR EACH ROW EXECUTE FUNCTION validate_library_word_core_v1_fn();
