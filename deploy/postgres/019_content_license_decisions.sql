CREATE TABLE IF NOT EXISTS content_license_decisions(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_key TEXT NOT NULL REFERENCES content_sources(source_key) ON DELETE RESTRICT,
 decision TEXT NOT NULL CHECK(decision IN ('pass','blocked')), evidence_url TEXT NOT NULL,
 reason TEXT NOT NULL, actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 actor_name TEXT NOT NULL, policy_version TEXT NOT NULL, occurred_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_content_license_decisions_source ON content_license_decisions(source_key,occurred_at,id);
CREATE OR REPLACE FUNCTION block_content_license_decision_changes() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RAISE EXCEPTION 'license decision log is immutable'; END$$;
DROP TRIGGER IF EXISTS immutable_content_license_decisions_update ON content_license_decisions;
CREATE TRIGGER immutable_content_license_decisions_update BEFORE UPDATE OR DELETE ON content_license_decisions FOR EACH ROW EXECUTE FUNCTION block_content_license_decision_changes();
