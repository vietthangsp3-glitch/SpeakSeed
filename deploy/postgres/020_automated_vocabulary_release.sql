CREATE TABLE IF NOT EXISTS vocabulary_automated_releases(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id BIGINT NOT NULL UNIQUE REFERENCES library_words(id) ON DELETE RESTRICT,
  source_candidate_ids_json TEXT NOT NULL,
  source_key TEXT NOT NULL,
  source_snapshot_sha256 TEXT NOT NULL,
  rule_version TEXT NOT NULL,
  checks_json TEXT NOT NULL,
  provenance_json TEXT NOT NULL,
  released_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_vocabulary_automated_releases_rule
  ON vocabulary_automated_releases(rule_version,released_at,word_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_library_words_published_normalized
  ON library_words(normalized_word) WHERE reviewed=1;
INSERT INTO vocabulary_quality_policies(version,core_requirements_json,enriched_fields_json,active,created_at)
VALUES('auto-core-v1',
 '["headword","part_of_speech","meaning_vi","cefr","field_provenance","publishable_license","automated_qa","deduplication"]',
 '["topic","ipa","example_en","example_vi","definition_en","synonym","antonym","word_form","collocation","multiple_senses"]',
 1,CURRENT_TIMESTAMP::text)
ON CONFLICT(version) DO NOTHING;

CREATE OR REPLACE FUNCTION validate_vocabulary_topic_publish_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.published=1 AND OLD.published=0 AND (
   NOT EXISTS(SELECT 1 FROM library_words w WHERE w.id=NEW.word_id AND w.reviewed=1)
   OR NOT (
     (NEW.review_status='human_reviewed' AND EXISTS(SELECT 1 FROM vocabulary_topic_reviews r
       WHERE r.word_id=NEW.word_id AND r.topic_id=NEW.topic_id AND r.sense_key=NEW.sense_key
         AND r.decision='approve' AND btrim(r.reviewer_name)<>''))
     OR (NEW.review_status='pending' AND NEW.source_key='automated-release-v1' AND NEW.confidence>=70
       AND EXISTS(SELECT 1 FROM vocabulary_automated_releases a
         WHERE a.word_id=NEW.word_id AND a.rule_version='auto-core-v1'))
   )) THEN RAISE EXCEPTION 'Human review or automated release evidence is required for a new topic mapping'; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS validate_vocabulary_topic_publish ON vocabulary_topic_words;
CREATE TRIGGER validate_vocabulary_topic_publish BEFORE UPDATE OF published ON vocabulary_topic_words
FOR EACH ROW EXECUTE FUNCTION validate_vocabulary_topic_publish_fn();

CREATE OR REPLACE FUNCTION validate_vocabulary_topic_publish_insert_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.published=1 AND NEW.review_status<>'existing_published' AND NOT (
   (NEW.review_status='human_reviewed' AND EXISTS(SELECT 1 FROM vocabulary_topic_reviews r
     WHERE r.word_id=NEW.word_id AND r.topic_id=NEW.topic_id AND r.sense_key=NEW.sense_key
       AND r.decision='approve' AND btrim(r.reviewer_name)<>''))
   OR (NEW.review_status='pending' AND NEW.source_key='automated-release-v1' AND NEW.confidence>=70
     AND EXISTS(SELECT 1 FROM vocabulary_automated_releases a
       WHERE a.word_id=NEW.word_id AND a.rule_version='auto-core-v1'))
 ) THEN RAISE EXCEPTION 'Human review or automated release evidence is required for a published topic mapping'; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS validate_vocabulary_topic_publish_insert ON vocabulary_topic_words;
CREATE TRIGGER validate_vocabulary_topic_publish_insert BEFORE INSERT ON vocabulary_topic_words
FOR EACH ROW EXECUTE FUNCTION validate_vocabulary_topic_publish_insert_fn();

CREATE OR REPLACE FUNCTION block_automated_release_changes() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'automated release evidence is immutable'; END $$;
DROP TRIGGER IF EXISTS immutable_vocabulary_automated_releases_update ON vocabulary_automated_releases;
CREATE TRIGGER immutable_vocabulary_automated_releases_update BEFORE UPDATE ON vocabulary_automated_releases
FOR EACH ROW EXECUTE FUNCTION block_automated_release_changes();
DROP TRIGGER IF EXISTS immutable_vocabulary_automated_releases_delete ON vocabulary_automated_releases;
CREATE TRIGGER immutable_vocabulary_automated_releases_delete BEFORE DELETE ON vocabulary_automated_releases
FOR EACH ROW EXECUTE FUNCTION block_automated_release_changes();
